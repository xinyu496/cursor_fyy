/*==============================================================
*FUNCTION NAME:校验和计算
*DISCRIPTION:校验和计算
*PARAMETERS:IN-需要校验的数据;OUT-ADD_CHECK
*RETURN:ADD_CHECK
*N/A
*NOTES:
*HISTORY:
*==============================================================*/
uint16_t UTL_ADD_CHECK(uint8_t *data,uint16_t length)
{
    uint16_t checksum = 0;
    for (uint16_t i = 0; i < length; i++)
    {
        checksum += data[i];
    }
    return checksum;
}

/*==============================================================
*FUNCTION NAME:校验和计算
*DISCRIPTION:校验和计算(求和取反版)
*PARAMETERS:IN-需要校验的数据;OUT-ADD_CHECK
*RETURN:ADD_CHECK
*N/A
*NOTES:
*HISTORY:
*==============================================================*/
uint16_t UTL_ADD_CHECK_REV(uint8_t *data,uint16_t length)
{
    uint16_t checksum = 0;
    for (uint16_t i = 0; i < length; i++)
    {
        checksum += data[i];
    }
    checksum = (~checksum);
    return checksum;
}
/*==============================================================
*FUNCTION NAME:异或校验
*DISCRIPTION:异或校验
*PARAMETERS:IN-需要校验的数据;OUT-XOR_CHECK
*RETURN:XOR_CHECK
*N/A
*NOTES:
*HISTORY:
*==============================================================*/
uint16_t UTL_XOR_CHECK(uint8_t *data,uint16_t len)
{
    uint16_t check_xor = 0;
    for(uint16_t i = 0; i < len; i++)
    {
        check_xor ^= data[i];
    }
    return check_xor;
}
/*==============================================================
*FUNCTION NAME:
*DISCRIPTION: 8位数反转
*PARAMETERS:
*RETURN:
*N/A
*NOTES:
*HISTORY:
*==============================================================*/
uint8_t InvertUint8(uint8_t data) {
    uint8_t temp = 0;

    for (int i = 0; i < 8; i++) {
        if (data & (1 << i)) {
            temp |= 1 << (7 - i);
        }
    }

    return temp;
}
/*==============================================================
*FUNCTION NAME:
*DISCRIPTION:16位数反转
*PARAMETERS:
*RETURN:
*N/A
*NOTES:
*HISTORY:
*==============================================================*/
uint16_t InvertUint16(uint16_t data) {
    uint16_t temp = 0;

    for (int i = 0; i < 16; i++) {
        if (data & (1 << i)) {
            temp |= 1 << (15 - i);
        }
    }

    return temp;
}
/*==============================================================
*FUNCTION NAME:CRC校验
*DISCRIPTION:ModbusCRC16
*PARAMETERS:IN-需要校验的数据;OUT-CRC_CHECK
*RETURN:CRC_CHECK
*N/A
*NOTES:
*HISTORY:
*==============================================================*/
uint16_t UTL_CRC_CHECK(uint8_t *data,uint16_t len)
{
    uint16_t check_crc = 0xffff;
    for(uint16_t i = 0; i < len; i++)
    {
        check_crc ^= data[i];
        for (int j = 0; j<8; j++)
        {
            uint8_t tmp = check_crc &0x0001;
            check_crc >>= 1;
            if (tmp)
            {
                check_crc ^= 0xA001;
            }
        }
    }
    return check_crc;
}
/*==============================================================
 * Function Name:UTL_MATH_Get_CRC8
 * Description:
 *	get crc8
 * Parameters:
 *	val       :
 * Return:crc8
 * Note:
 *	N/A
 * History:
*==============================================================*/
uint8_t UTL_Get_CRC8(uint8_t *ptr, uint16_t len)
{
	uint8_t crc;
	uint8_t i;
	crc = 0;
	while(len--)
	{
		crc ^= *ptr++;
		for(i = 0; i < 8; i++)
		{
			if(crc&0x01)
			{
				crc = (crc>>1)^0x8C;
			}
			else
			{
				crc >>= 1;
			}
		}
	}
	return crc;
}
/*==============================================================
 * Function Name:CRC16_CCITT_FALSE
 * Description: get crc8
 * Parameters:
 *	val       :
 * Return:crc8
 * Note:
 *	N/A
 * History:
*==============================================================*/
uint16_t UTL_CRC16_CCITT_FALSE(uint8_t* pMsg, uint32_t size) {
    uint16_t value = 0xFFFF;
    uint16_t poly = 0x1021;

    while (size--) {
        uint8_t input = *(pMsg++);
        value ^= (input << 8);

        for (int i = 0; i < 8; i++) {
            if (value & 0x8000) {
                value = (value << 1) ^ poly;
            } else {
                value = value << 1;
            }
        }
    }
    return (value);
}
/*==============================================================
 * Function Name:	CRC16_CCITT
 * Description:get crc16
 * Parameters:
 *	val:
 * Return: crc8
 * Note:
 *	N/A
 * History:
*==============================================================*/
uint16_t UTL_CRC16_CCITT(uint8_t* pMsg, uint32_t size)
{
    uint16_t value = 0x0000;
    uint16_t poly = 0x1021;

    while (size--) {
        uint8_t input = InvertUint8 (*(pMsg++));
        value ^= (input << 8);

        for (int i = 0; i < 8; i++) {
            if (value & 0x8000) {
                value = (value << 1) ^ poly;
            } else {
                value = value << 1;
            }
        }
    }
    value = InvertUint16(value);//高低位取反

    return value;
}

/*===================================================================
 * FUNCTION NAME:UTL_FletCher16
 * DESCRIPTION:累加和取模
 *	N/A
 * PARAMETERS:
 *	I16Ulen   :
 * RETURN:
 *	N/A
 * NOTES:
 *	N/A
 * HISTORY:
 *=================================================================*/
uint16_t UTL_FletCher16(const uint8_t *pbuf, uint16_t len)
{
	uint16_t cs1,cs2;

	cs1= cs2= 0;

	while(len--)
	{
		cs1 += *pbuf++;
		cs2 += cs1;
	}

	return (cs2 << 8) |(cs1 & 0xFF);
}




